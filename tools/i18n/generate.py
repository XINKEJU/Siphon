def extract_english():
    text = open(SWIFT, encoding="utf-8").read()
    m = re.search(r'private let English: \[String: String\] = \[(.*?)\n\]', text, re.S)
    if not m:
        raise SystemExit("English catalog not found")
    body = m.group(1)
    pairs = re.findall(r'"([^"]+)":\s*"([^"]*)"', body)
    return pairs


def main():
    os.makedirs(OUT, exist_ok=True)
    pairs = extract_english()
    manifest = []
    for code, name in LANGUAGES:
        trans = TRANSLATIONS.get(code, {})
        lines = ["# language=" + code, "# name=" + name]
        status = "reviewed" if code in TRANSLATIONS else "machine"
        lines.append("# status=" + status)
        for key, en in pairs:
            val = trans.get(key, en)
            # TSV: escape tabs and newlines conservatively
            val = val.replace("\t", " ").replace("\n", " ")
            lines.append(f"{key}\t{val}")
        with open(os.path.join(OUT, code + ".tsv"), "w", encoding="utf-8") as f:
            f.write("\n".join(lines) + "\n")
        manifest.append((code, name, status))
    with open(os.path.join(OUT, "manifest.tsv"), "w", encoding="utf-8") as f:
        f.write("code\tname\tstatus\n")
        for code, name, status in manifest:
            f.write(f"{code}\t{name}\t{status}\n")
    print(f"generated {len(LANGUAGES)} languages")


if __name__ == "__main__":
    main()
